@pytest.mark.django_db
def test_get_intended_use_returns_200(authenticated_api_client):
    from credentials.serializers import create_intended_use

    entity = RegisteredEntityFactory()
    iu = create_intended_use(entity, _IU_PAYLOAD)
    response = authenticated_api_client.get(_detail_url(entity.pk, iu.pk))
    assert response.status_code == status.HTTP_200_OK
    assert response.data["intendedUseIdentifier"] == iu.intended_use_identifier


@pytest.mark.django_db
def test_get_intended_use_wrong_entity_returns_404(authenticated_api_client):
    """Cannot access an intended use via a different entity's URL."""
    from credentials.serializers import create_intended_use

    entity = RegisteredEntityFactory()
    other_entity = RegisteredEntityFactory()
    iu = create_intended_use(entity, _IU_PAYLOAD)
    response = authenticated_api_client.get(_detail_url(other_entity.pk, iu.pk))
    assert response.status_code == status.HTTP_404_NOT_FOUND


