@pytest.mark.django_db
def test_revoke_sets_validity_end(authenticated_api_client):
    from datetime import date

    from credentials.serializers import create_intended_use

    entity = RegisteredEntityFactory()
    iu = create_intended_use(entity, _IU_PAYLOAD)
    authenticated_api_client.delete(_detail_url(entity.pk, iu.pk))
    iu.refresh_from_db()
    assert iu.validity_end == date.today()


@pytest.mark.django_db
def test_revoke_is_idempotent(authenticated_api_client):
    from credentials.serializers import create_intended_use

    entity = RegisteredEntityFactory()
    iu = create_intended_use(entity, _IU_PAYLOAD)
    authenticated_api_client.delete(_detail_url(entity.pk, iu.pk))
    response = authenticated_api_client.delete(_detail_url(entity.pk, iu.pk))
    assert response.status_code == status.HTTP_204_NO_CONTENT
